-- TABLE 1: USERS
CREATE TABLE users (
    id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR2(100) NOT NULL,
    email       VARCHAR2(120) NOT NULL CONSTRAINT uq_users_email UNIQUE,
    role        VARCHAR2(30) DEFAULT 'STUDENT' NOT NULL,
    department  VARCHAR2(100),
    created_at  TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT chk_user_role CHECK (role IN ('STUDENT', 'FACULTY', 'ADMIN', 'STAFF'))
);

-- TABLE 2: BUILDINGS
CREATE TABLE buildings (
    id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR2(20) NOT NULL CONSTRAINT uq_buildings_code UNIQUE,
    name        VARCHAR2(100) NOT NULL,
    floors      NUMBER DEFAULT 4 NOT NULL,
    map_x       NUMBER NOT NULL,
    map_y       NUMBER NOT NULL,
    description CLOB,
    status      VARCHAR2(30) DEFAULT 'OPERATIONAL' NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT chk_building_status CHECK (status IN ('OPERATIONAL', 'PARTIAL', 'MAINTENANCE')),
    CONSTRAINT chk_building_floors_positive CHECK (floors > 0)
);

-- TABLE 3: ROOMS
CREATE TABLE rooms (
    id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building_id   NUMBER NOT NULL CONSTRAINT fk_rooms_building REFERENCES buildings(id) ON DELETE CASCADE,
    room_number   VARCHAR2(20) NOT NULL,
    floor         NUMBER DEFAULT 1 NOT NULL,
    capacity      NUMBER NOT NULL,
    room_type     VARCHAR2(30) DEFAULT 'CLASSROOM' NOT NULL,
    status        VARCHAR2(30) DEFAULT 'AVAILABLE' NOT NULL,
    has_projector NUMBER(1) DEFAULT 1 NOT NULL,
    has_ac        NUMBER(1) DEFAULT 1 NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT chk_room_capacity_positive CHECK (capacity > 0),
    CONSTRAINT chk_room_status CHECK (status IN ('AVAILABLE', 'OCCUPIED', 'MAINTENANCE')),
    CONSTRAINT chk_room_type CHECK (room_type IN ('CLASSROOM', 'LAB', 'AUDITORIUM', 'CONFERENCE', 'STUDY_POD')),
    CONSTRAINT chk_rooms_projector CHECK (has_projector IN (0, 1)),
    CONSTRAINT chk_rooms_ac CHECK (has_ac IN (0, 1)),
    CONSTRAINT uq_building_room_number UNIQUE (building_id, room_number)
);

